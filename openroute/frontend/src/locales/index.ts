const dictionaries: Record<Lang, Record<string, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
}

const LANG_STORAGE_KEY = 'openroute_lang'

/** 读取本地缓存的语言。 */
function readCachedLang(): Lang {
  const cached = localStorage.getItem(LANG_STORAGE_KEY)
  return cached === 'en-US' ? 'en-US' : 'zh-CN'
}

interface I18nState {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: string, vars?: Record<string, string | number>) => string
}

export const useI18n = create<I18nState>((set, get) => ({
  lang: readCachedLang(),

  setLang: (lang) => {
    localStorage.setItem(LANG_STORAGE_KEY, lang)
    set({ lang })
  },

  t: (key, vars) => {
    const { lang } = get()
    // 回退顺序：当前语言 → 中文（权威）→ 键名本身。
    const dict = dictionaries[lang]
    let text = dict[key] ?? zhCN[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(new RegExp(`\\{\\{${k}\\}\\}`, 'g'), String(v))
      }
    }
    return text
  },
}))

/** 在非组件环境中取翻译函数（如表格列定义、消息提示）。 */
export function t(key: string, vars?: Record<string, string | number>): string {
  return useI18n.getState().t(key, vars)
}
